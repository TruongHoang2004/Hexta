#!/usr/bin/env python3
"""Read-only instruction checks; explicit --sync-adapters updates owned adapters only."""
from __future__ import annotations
import argparse
import fnmatch
import json
from pathlib import Path
import re
import tempfile
import unittest
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[1]
GENERATED = '<!-- Generated by scripts/check-agent-instructions.py; edit canonical sources. -->'
NEW_SKILLS = ('frontend-component-discovery', 'frontend-feature-development',
              'backend-feature-development', 'ai-feature-development', 'cross-service-change', 'code-review')
DOMAINS = ('apps', 'apps/web', 'apps/admin', 'apps/docs', 'apps/landing', 'services/api',
           'services/ai', 'packages/ui', 'packages/sdk', 'packages/shared', 'proto', 'migrations', 'infrastructure')
LINK = re.compile(r'\[[^\]\n]+\]\(([^)\n]+)\)')


def metadata(text: str) -> dict[str, str]:
    if not text.startswith('---\n') or '\n---\n' not in text[4:]:
        raise ValueError('missing YAML frontmatter')
    result = {}
    for line in text[4:].split('\n---\n', 1)[0].splitlines():
        if line.startswith((' ', '\t', '#')) or ':' not in line:
            continue
        key, value = line.split(':', 1)
        value = value.strip()
        if value.startswith('"'):
            value = json.loads(value)
        elif value.startswith("'") and value.endswith("'"):
            value = value[1:-1].replace("''", "'")
        result[key] = value
    return result


def routes(root: Path) -> list[tuple[str, list[str], list[str]]]:
    text = (root / 'rules/README.md').read_text()
    block = text.split('<!-- agent-scope-routes:start -->', 1)[1].split('<!-- agent-scope-routes:end -->', 1)[0]
    result = []
    for line in block.splitlines():
        if not line.startswith('| ') or '`' not in line:
            continue
        columns = [c.strip() for c in line.strip('|').split('|')]
        name = columns[0]
        globs = [g.strip() for g in columns[1].strip('`').split(',')]
        entries = [(root / 'rules' / target).resolve().relative_to(root.resolve()).as_posix()
                   for target in LINK.findall(columns[2])]
        if not re.fullmatch(r'[a-z][a-z-]*', name) or not globs or not entries:
            raise ValueError(f'invalid route: {line}')
        if name in {row[0] for row in result}:
            raise ValueError(f'duplicate route: {name}')
        result.append((name, globs, entries))
    if not result:
        raise ValueError('no domain routes')
    return result


def expected_adapters(root: Path) -> dict[str, str]:
    result = {'CLAUDE.md': '@AGENTS.md\n', **{f'{d}/CLAUDE.md': '@AGENTS.md\n' for d in DOMAINS}}
    for name, globs, entries in routes(root):
        links = ', '.join(f'[{entry}](../../{entry})' for entry in entries)
        result[f'.agents/rules/scope-{name}.md'] = (
            '---\ntrigger: glob\nglobs: ' + json.dumps(', '.join(globs)) + '\n'
            + 'description: ' + json.dumps(f'Select Hexta {name} instructions for matching files.')
            + '\n---\n\n' + GENERATED + '\n\n'
            + f'Before editing matching files, read {links} unless already loaded. '
            + 'Read applicable ancestor/app-local AGENTS and reselect affected consumers through '
            + '[the root router](../../rules/README.md). This is a context selector, not a policy body.\n')
    for source in sorted((root / '.agents/skills').glob('*/SKILL.md')):
        info = metadata(source.read_text())
        name, description = info.get('name', ''), info.get('description', '')
        if name != source.parent.name or not re.fullmatch(r'[a-z0-9-]{1,63}', name) or not description:
            raise ValueError(f'invalid skill metadata: {source.relative_to(root)}')
        hint = re.search(r'^  claude-argument-hint: (.+)$', source.read_text(), re.M)
        hint_line = f'argument-hint: {hint.group(1)}\n' if hint else ''
        result[f'.claude/skills/{name}/SKILL.md'] = (
            f'---\nname: {name}\ndescription: {json.dumps(description)}\n' + hint_line + '---\n\n' + GENERATED + '\n\n'
            + f'Read and follow [the canonical {name} workflow](../../../.agents/skills/{name}/SKILL.md) '
            + 'before acting. Resolve its resources relative to that canonical skill directory, '
            + 'not this adapter. Do not load sibling skills unless the selected workflow requires them. '
            + 'Preserve the user task scope and authorization.\n')
    return result


def sync(root: Path, expected: dict[str, str]) -> None:
    # Preflight every destination before writing; never delete or overwrite handwritten adapters.
    for relative, content in expected.items():
        path = root / relative
        if path.is_symlink():
            raise ValueError(f'refusing symlink adapter: {relative}')
        if path.exists() and path.read_text() != content and GENERATED not in path.read_text():
            raise ValueError(f'refusing handwritten adapter: {relative}')
    for relative, content in expected.items():
        path = root / relative
        if not path.exists() or path.read_text() != content:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


def selected(root: Path, target: str) -> set[str]:
    """Declared coverage, not simulation of a client's discovery engine."""
    found = {'AGENTS.md'}
    for _, globs, entries in routes(root):
        if any(fnmatch.fnmatchcase(target, pattern) for pattern in globs):
            found.update(entries)
    for parent in (root / target).parents:
        if parent == root or not parent.is_relative_to(root):
            break
        local = parent / 'AGENTS.md'
        if local.exists():
            found.add(local.relative_to(root).as_posix())
    return found


def broken_links(root: Path, relative: str) -> list[str]:
    path = root / relative
    text = re.sub(r'```.*?```', '', path.read_text(), flags=re.S)
    failures = []
    for target in LINK.findall(text):
        target = target.strip('<>').split('#', 1)[0]
        if not target or re.match(r'[a-zA-Z][a-zA-Z0-9+.-]*:', target):
            continue
        if not (path.parent / unquote(target)).exists():
            failures.append(f'{relative}: missing link {target}')
    return failures


def check(root: Path) -> tuple[list[str], list[str]]:
    errors, warnings = [], []
    expected = expected_adapters(root)
    for relative, content in expected.items():
        path = root / relative
        if not path.exists() or path.read_text() != content:
            errors.append(f'adapter drift/missing: {relative}')
        if len(content.encode()) > 1500:
            errors.append(f'adapter exceeds 1500 bytes: {relative}')
    for pattern in ('.agents/rules/scope-*.md', '.claude/skills/*/SKILL.md'):
        for path in root.glob(pattern):
            if path.relative_to(root).as_posix() not in expected:
                errors.append(f'unmapped adapter (review, do not auto-delete): {path.relative_to(root)}')
    canonical = ['AGENTS.md', *[f'{d}/AGENTS.md' for d in DOMAINS], 'rules/README.md',
                 'rules/frontend.md', 'agentic-memory/README.md', 'docs/architecture/ai-instructions.md',
                 '.agents/rules/agentic-memory.md', '.agents/rules/skill-execution-protocol.md',
                 *[f'.agents/skills/{name}/SKILL.md' for name in NEW_SKILLS]]
    for relative in canonical:
        path = root / relative
        if not path.exists():
            errors.append(f'missing canonical file: {relative}')
            continue
        errors.extend(broken_links(root, relative))
        limit = 14000 if relative == 'rules/README.md' else (4000 if '/skills/' in relative else
                                                           5000 if relative.endswith('AGENTS.md') else None)
        if limit and path.stat().st_size > limit:
            errors.append(f'budget exceeded ({limit} bytes): {relative}')
    for relative in expected:
        if (root / relative).exists():
            errors.extend(broken_links(root, relative))
    for path in (root / '.agents/rules').glob('*.md'):
        info = metadata(path.read_text())
        if info.get('trigger') not in ('always_on', 'model_decision', 'glob', 'manual'):
            errors.append(f'invalid trigger: {path.relative_to(root)}')
        if info.get('trigger') == 'model_decision' and not info.get('description'):
            errors.append(f'missing description: {path.relative_to(root)}')
        if info.get('trigger') == 'glob' and not info.get('globs'):
            errors.append(f'missing globs: {path.relative_to(root)}')
    for path in (root / '.agents/skills').glob('*/SKILL.md'):
        relative = path.relative_to(root).as_posix()
        if relative not in canonical:
            warnings.extend(broken_links(root, relative))
    fixtures = [
        ('apps/web/components/new-form.tsx', {'apps/AGENTS.md', 'apps/web/AGENTS.md'}, {'services/api/AGENTS.md'}),
        ('services/api/internal/core/service/messaging_service.go', {'services/api/AGENTS.md'}, {'apps/AGENTS.md'}),
        ('services/ai/hexta_ai/providers/base.py', {'services/ai/AGENTS.md'}, {'apps/AGENTS.md', 'services/api/AGENTS.md'}),
        ('proto/hexta/ai/v1/service.proto', {'proto/AGENTS.md'}, set()),
        ('packages/ui/src/components/button.tsx', {'packages/ui/AGENTS.md'}, set()),
        ('infrastructure/compose.demo.yml', {'infrastructure/AGENTS.md'}, set()),
        ('atlas.hcl', {'migrations/AGENTS.md'}, set()),
        ('services/ai/generated/hexta/ai/v1/service_pb2.py', {'proto/AGENTS.md', 'services/ai/AGENTS.md'}, set()),
        ('packages/shared/proto/identity.proto', {'packages/shared/AGENTS.md'}, {'proto/AGENTS.md'}),
        ('Dockerfile.migrate', {'infrastructure/AGENTS.md', 'migrations/AGENTS.md'}, set()),
        ('apps/admin/app/page.tsx', {'apps/AGENTS.md', 'apps/admin/AGENTS.md'}, {'apps/web/AGENTS.md'}),
    ]
    for target, required, forbidden in fixtures:
        actual = selected(root, target)
        if not required <= actual or forbidden & actual:
            errors.append(f'route fixture failed: {target}: {sorted(actual)}')
    return errors, warnings


class ValidatorTests(unittest.TestCase):
    def test_metadata_requires_frontmatter(self):
        with self.assertRaises(ValueError):
            metadata('# missing metadata')
        self.assertEqual(metadata('---\nname: demo\ndescription: "A: B"\n---\n')['description'], 'A: B')

    def test_sync_refuses_handwritten_before_writing(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            (root / 'existing.md').write_text('human policy')
            with self.assertRaises(ValueError):
                sync(root, {'new.md': 'new', 'existing.md': 'replacement'})
            self.assertFalse((root / 'new.md').exists())
            self.assertEqual((root / 'existing.md').read_text(), 'human policy')

    def test_sync_idempotent_and_no_deletion(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            (root / 'unrelated.md').write_text('retain')
            expected = {'nested/adapter.md': GENERATED + '\nreference\n'}
            sync(root, expected)
            timestamp = (root / 'nested/adapter.md').stat().st_mtime_ns
            sync(root, expected)
            self.assertEqual((root / 'nested/adapter.md').stat().st_mtime_ns, timestamp)
            self.assertEqual((root / 'unrelated.md').read_text(), 'retain')

    def test_claude_hint_translation_and_canonical_body_reference(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            (root / 'rules').mkdir()
            (root / 'rules/README.md').write_text(
                '<!-- agent-scope-routes:start -->\n'
                '| api | `services/api/**` | [API](../services/api/AGENTS.md) |\n'
                '<!-- agent-scope-routes:end -->\n')
            skill = root / '.agents/skills/demo/SKILL.md'
            skill.parent.mkdir(parents=True)
            skill.write_text('---\nname: demo\ndescription: Example workflow\nmetadata:\n'
                             '  claude-argument-hint: "[target]"\n---\nCANONICAL BODY\n')
            adapter = expected_adapters(root)['.claude/skills/demo/SKILL.md']
            self.assertIn('argument-hint: "[target]"', adapter)
            self.assertIn('../../../.agents/skills/demo/SKILL.md', adapter)
            self.assertNotIn('CANONICAL BODY', adapter)
            self.assertNotIn('claude-argument-hint', metadata(skill.read_text()))

    def test_missing_link_and_external_link(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            (root / 'doc.md').write_text('[missing](gone.md) [remote](https://example.com)')
            self.assertEqual(broken_links(root, 'doc.md'), ['doc.md: missing link gone.md'])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sync-adapters', action='store_true')
    parser.add_argument('--self-test', action='store_true')
    args = parser.parse_args()
    if args.self_test:
        result = unittest.TextTestRunner().run(unittest.defaultTestLoader.loadTestsFromTestCase(ValidatorTests))
        if not result.wasSuccessful():
            return 1
    try:
        if args.sync_adapters:
            sync(ROOT, expected_adapters(ROOT))
        errors, warnings = check(ROOT)
    except (ValueError, IndexError, KeyError, OSError) as error:
        print(f'FAIL: {error}')
        return 1
    for warning in warnings:
        print(f'LEGACY WARNING: {warning}')
    for error in errors:
        print(f'FAIL: {error}')
    print(f'{"FAIL" if errors else "PASS"}: instruction structure, adapters, budgets and 11 declared route fixtures; '
          f'{len(errors)} errors, {len(warnings)} legacy link warnings. Native-client behavior NOT_RUN.')
    return int(bool(errors))


if __name__ == '__main__':
    raise SystemExit(main())
